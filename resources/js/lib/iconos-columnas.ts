/** "Área / Bahía" -> "area / bahia". */
function normalizar(texto: string): string {
    return texto
        .normalize('NFD')
        .replace(/[̀-ͯ]/g, '')
        .trim()
        .toLowerCase();
}

/** El ícono de una columna por su título; nulo si no tiene uno asignado. */
export function iconoDeColumna(titulo: unknown): LucideIcon | null {
    return typeof titulo === 'string' && titulo !== ''
        ? (ICONOS[normalizar(titulo)] ?? null)
        : null;
}
